// Postgres data layer.
//  - DATABASE_URL set  -> hosted Postgres (e.g. Supabase) through a connection pool
//  - otherwise         -> embedded Postgres (PGlite) stored in KANZ_DATA_DIR (default data/pgdata), no setup needed
// The tiny wrapper below keeps the `db.prepare(sql).get/all/run(...params)` style (now async) and accepts
// `?` / `?N` placeholders, so the SQL stays readable.
import pg from 'pg';
import { PGlite } from '@electric-sql/pglite';
import { AsyncLocalStorage } from 'node:async_hooks';
import { mkdirSync } from 'node:fs';

const toNumber = (v) => (v === null ? null : Number(v));
const DATABASE_URL = process.env.DATABASE_URL;
export const BACKEND = DATABASE_URL ? 'postgres' : 'pglite';

let pool, lite;
if (DATABASE_URL) {
  pg.types.setTypeParser(20, toNumber);   // bigint
  pg.types.setTypeParser(1700, toNumber); // numeric
  const ssl = process.env.DATABASE_SSL === 'false' ? false : { rejectUnauthorized: false };
  pool = new pg.Pool({ connectionString: DATABASE_URL, ssl, max: Number(process.env.DATABASE_POOL_MAX) || 5 });
  pool.on('error', (e) => console.error('Postgres pool error:', e.message));
} else {
  const dir = process.env.KANZ_DATA_DIR || new URL('../data/pgdata', import.meta.url).pathname;
  if (!dir.startsWith('memory://')) mkdirSync(dir, { recursive: true });
  lite = await PGlite.create(dir, { parsers: { 20: toNumber, 1700: toNumber } });
}

const als = new AsyncLocalStorage();
const baseExec = async (sql, params) => {
  if (pool) { const r = await pool.query(sql, params); return { rows: r.rows, count: r.rowCount ?? 0 }; }
  const r = await lite.query(sql, params);
  return { rows: r.rows, count: r.affectedRows ?? r.rows.length };
};

function convert(sql) {
  if (/\?\d/.test(sql)) return sql.replace(/\?(\d+)/g, '$$$1');
  let n = 0;
  return sql.replace(/\?/g, () => `$${++n}`);
}

const HAS_ID = /^\s*INSERT\s+INTO\s+(\w+)/i;
async function exec(sql, params) {
  const ex = als.getStore() ?? baseExec;
  return ex(sql, params.map((p) => (p === undefined ? null : p)));
}

export const db = {
  prepare(sql) {
    const text = convert(sql);
    return {
      get: async (...p) => (await exec(text, p)).rows[0],
      all: async (...p) => (await exec(text, p)).rows,
      run: async (...p) => {
        const m = HAS_ID.exec(text);
        const withId = m && m[1] !== 'settings' && !/RETURNING/i.test(text);
        const r = await exec(withId ? `${text} RETURNING id` : text, p);
        return { lastInsertRowid: r.rows[0]?.id, changes: r.count };
      },
    };
  },
  exec: async (sql) => { if (pool) await pool.query(sql); else await lite.exec(sql); },
};

export async function tx(fn) {
  if (als.getStore()) return fn(); // already inside a transaction: join it
  if (pool) {
    const c = await pool.connect();
    const run = async (sql, params) => { const r = await c.query(sql, params); return { rows: r.rows, count: r.rowCount ?? 0 }; };
    try {
      await c.query('BEGIN');
      const out = await als.run(run, fn);
      await c.query('COMMIT');
      return out;
    } catch (e) { await c.query('ROLLBACK').catch(() => {}); throw e; } finally { c.release(); }
  }
  return lite.transaction((t) => als.run(async (sql, params) => { const r = await t.query(sql, params); return { rows: r.rows, count: r.affectedRows ?? r.rows.length }; }, fn));
}

const TABLES = ['users', 'settings', 'customers', 'suppliers', 'products', 'stock_moves', 'sales', 'sale_items', 'purchases', 'purchase_items', 'cashbook', 'audit_log', 'import_issues'];
